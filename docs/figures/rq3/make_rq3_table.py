"""Paper Tab. 3: task success of the Qwen3.5-4B configurations on the four benchmarks, one column wide (user, 2026-10-06:
the bar panel of the results figure became this table). Runs come from rq3_config.yaml (single agent and planner,
untrained or trained) and data_config.yaml (the executor trained on InSTA's data), as for the figures.

Rows are grouped as Tab. 1 groups them (italic bold headings), set at the caption's size (\small, user 2026-10-06:
bigger text). Colour, as in Tab. 2 and Fig. 7: a row's data source is named in its Fig. 7 colour (grey: nothing, brown:
InSTA, blue: ours), and a cell is green (red) when it is significantly above (below) the untrained row of its group,
p < 0.05 by the test of make_rq3.stars (paired permutation over tasks on MiniWeb and WebArena-Lite, exact McNemar on the
live web); the text gives the p-values.

    python docs/figures/rq3/make_rq3_table.py [--out docs/figures/rq3/rq3_table.tex]
"""
import argparse, os, statistics as st, sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
FIGS = os.path.dirname(HERE)
for d in ("common", "tables"):
    sys.path.insert(0, os.path.join(FIGS, d))
sys.path.insert(0, HERE)
from results import ROOT, task_rates  # noqa: E402
from make_rq3 import stars  # noqa: E402

HEAD = [("miniweb", r"\miniweb{}", "63"), ("wa", "WA-Lite", "154"), ("wv", "WV", "536"), ("om2w", "OM2W", "280")]
GROUPS = [("Single agent, trained on", [("nothing", "Single agent, untrained", "untrained"),
                                        ("our data", "Single agent, trained", "ours")]),
          ("Planner, executor trained on", [("nothing", "Planner, untrained", "untrained"),
                                            ("InSTA's data", "+ task-centric data (InSTA)", "insta"),
                                            (r"\textbf{\miniwebagent{}}", "MiniWebAgent", "ours")])]   # each group's
COLOR = {"untrained": "7D8798", "insta": "A8520F", "ours": "2B5C9E"}   # first row is its baseline; Fig. 7's colours
OURS = "MiniWebAgent"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "rq3_table.tex"))
    out = ap.parse_args().out
    rq3 = yaml.safe_load(open(os.path.join(HERE, "rq3_config.yaml")))
    data = yaml.safe_load(open(os.path.join(HERE, "data_config.yaml")))
    arms = {a["label"]: a for a in data["arms"] + rq3["arms"]}   # rq3_config wins on shared labels (it has every benchmark)
    bench = {b["key"]: b for b in rq3["benchmarks"]}
    mean = lambda a, k: st.mean(task_rates(bench[k]["kind"], a[k], bench[k].get("tasks"))) if a.get(k) else None
    L = ["% generated by docs/figures/rq3/make_rq3_table.py from rq3_config.yaml and data_config.yaml; do not edit by hand",
         *[r"\providecolor{mwt" + k + "}{HTML}{" + v + "}" for k, v in COLOR.items()],
         r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{4pt}",
         r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
         " & " + " & ".join(h for _, h, _ in HEAD) + r" \\",
         r"\textcolor{gray}{\footnotesize tasks} & " + " & ".join(r"\textcolor{gray}{\footnotesize " + n + "}"
                                                              for _, _, n in HEAD) + r" \\", r"\midrule"]
    for gi, (head, rows) in enumerate(GROUPS):
        if gi:
            L.append(r"\addlinespace[3pt]")
        L.append(r"\multicolumn{5}{@{}l}{\textit{\textbf{" + head + r"}}} \\")
        base = arms[rows[0][1]]
        for name, label, col in rows:
            a, cells = arms[label], []
            for k, _, _ in HEAD:
                m = mean(a, k)
                if m is None:
                    cells.append("--")
                    continue
                c = r"\textbf{" + f"{m:.1f}" + "}" if label == OURS else f"{m:.1f}"
                if a is not base and stars(bench[k], base, a):          # p < 0.05 against the group's untrained row
                    c = r"\cellcolor{" + ("green!18" if m > mean(base, k) else "red!18") + "}" + c
                cells.append(c)
            L.append(r"\hspace{0.6em}\textcolor{mwt" + col + "}{" + name + "} & " + " & ".join(cells) + r" \\")
            print(f"  {label:32s}", " ".join(f"{c:>22s}" for c in cells))
    L += [r"\bottomrule", r"\end{tabular}",
          r"\caption{\textbf{Composing trained skills raises task success.} Task success (\%) of Qwen3.5-4B on "
          r"\miniweb{}'s held-out sites, WebArena-Lite (WA-Lite), WebVoyager (WV), and Online-Mind2Web (OM2W), as a "
          r"single agent or as a planner whose executor is untrained or trained at matched size on InSTA's "
          r"task-centric data or on ours. Green (red): significantly above (below) the untrained row of the group, "
          r"$p<0.05$. \textbf{Takeaway:} our data raises task success only under the planner, where it beats both "
          r"the untrained executor and InSTA's on every benchmark.}",
          r"\label{tab:rq3}", r"\end{table}", ""]
    open(out, "w").write("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    main()
