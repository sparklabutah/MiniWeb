"""Expand transit-directions (Lakeport Transit Authority) base data.

The site ships with 848 rows total (schedules: 629, stops: 171, routes: 30,
trip_plans: 8, routes_transit: 6, plus users/fares). The bulk of the expansion
goes into `schedules` (GTFS-style stop_times): each of the 29 routes with
existing trips gets many more service runs through the day, generated by
replaying the route's existing trip patterns (same stop_id/stop_name/sequence,
same inter-stop offsets) at new seeded departure times. Also adds ~280 new
street-corner stops in the existing Lakeport naming style and 24 saved trip
plans for the three existing users, reusing the routes_transit vocabulary.

Referential integrity: new schedule rows only reference existing route_id /
stop_id / stop_name triples taken verbatim from existing trips; trip plans
reference existing users and Route 1-6X names. Per-route schedule row counts
stay under ~200 so the /route/<id> detail pages remain small.

Insert-only -- existing rows are never touched. Inserted ids are recorded in
data/backups/transit-directions-expansion-2026-07-20/inserted_ids.json.

Usage: ~/.conda/envs/miniweb/bin/python scripts/expand_transit_directions_data.py [--dry-run]
"""
